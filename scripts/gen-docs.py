#!/usr/bin/env python3
"""Regenerate docs/agents.md and docs/skills.md.

Sources of truth:
  - Grouping and one-line summaries: the tables in README.md
    ("## The Team" section for agents, "## Skills" section for skills).
  - Everything else: the YAML frontmatter of agents/*.md and skills/*.md.

  - The roster table inside agents/founder.md (between the ROSTER markers)
    is generated from the same README tables.

Usage:
  scripts/gen-docs.py          # write the docs
  scripts/gen-docs.py --check  # exit 1 if the docs are out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATED = "<!-- Generated by scripts/gen-docs.py from README.md and frontmatter. Do not edit by hand. -->"


sys.path.insert(0, str(ROOT / "scripts"))
from build import parse_frontmatter  # noqa: E402


def frontmatter(path):
    try:
        return parse_frontmatter(path)[0]
    except ValueError:
        return None


def section(text, heading):
    start = text.index(heading)
    nxt = re.search(r"^## ", text[start + len(heading):], re.M)
    return text[start: start + len(heading) + nxt.start()] if nxt else text[start:]


def readme_groups(heading, row_re):
    """Return [(group_title, [(key, summary), ...]), ...] from README tables."""
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    groups, current = [], None
    for line in section(readme, heading).splitlines():
        h = re.match(r"^### (.+?)\s*(?:\(\d+\))?\s*$", line)
        if h:
            current = (h.group(1), [])
            groups.append(current)
            continue
        r = re.match(row_re, line)
        if r and current is not None:
            current[1].append((r.group(1), r.group(2).strip()))
    return [g for g in groups if g[1]]


def agents_doc():
    groups = readme_groups("## The Team", r"^\| `([a-z0-9-]+)` \| (.+?) \|$")
    meta = {}
    for p in sorted((ROOT / "agents").glob("*.md")):
        fm = frontmatter(p)
        if fm and "name" in fm:
            meta[fm["name"]] = fm
    specialists = sum(1 for n in meta if not n.startswith("team-"))
    coordinators = sum(1 for n in meta if n.startswith("team-"))

    out = [
        GENERATED,
        "",
        "# Agent Capability Reference",
        "",
        f"All {specialists} specialist agents and {coordinators} team coordinators, with the tier and capabilities each one runs with.",
        "",
        "## How to invoke an agent",
        "",
        "In Claude Code, name the agent you want:",
        "",
        "```",
        "Use the ai-architect agent to design a scalable architecture for my AI SaaS.",
        "```",
        "",
        "Or let a routing skill pick:",
        "",
        "```",
        '/cofounder "design a scalable architecture for my AI SaaS"',
        "```",
        "",
        "**Tier** is how much reasoning the agent needs (`deep`, `standard`, `fast`); each workspace maps it to its own models. "
        "**Capabilities** (`read`, `edit`, `shell`, `web`, `delegate`) map to each workspace's tools.",
        "",
    ]
    seen = set()
    for title, rows in groups:
        rows = [(n, s) for n, s in rows if n not in seen]
        if not rows:
            continue
        out += ["---", "", f"## {title} ({len(rows)})", ""]
        for name, summary in rows:
            seen.add(name)
            fm = meta.get(name)
            out.append(f"### `{name}`")
            if fm is None:
                out += [f"**Missing:** no `agents/{name}.md` file.", ""]
                continue
            label = "Delegates to" if name.startswith("team-") else "Best for"
            out += [
                f"**Tier**: `{fm.get('tier', 'standard')}` · **Capabilities**: {', '.join(fm.get('capabilities', []))}  ",
                f"**{label}**: {summary}",
                "",
                fm.get("description", ""),
                "",
            ]
    missing = sorted(set(meta) - seen)
    if missing:
        out += ["---", "", "## Not yet grouped in README", ""]
        for name in missing:
            out += [f"### `{name}`", "", meta[name].get("description", ""), ""]
    return "\n".join(out).rstrip() + "\n"


def skills_doc():
    groups = readme_groups("## Skills", r"^\| `/([a-z0-9-]+)[^`]*` \| (.+?) \|$")
    meta = {p.parent.name: frontmatter(p) or {} for p in sorted((ROOT / "skills").glob("*/SKILL.md"))}
    out = [
        GENERATED,
        "",
        f"# Skills Reference — {len(meta)} Skills",
        "",
        "Skills follow the open [Agent Skills](https://agentskills.io) standard and work in Claude Code, Cursor, GitHub Copilot, Codex, Gemini CLI "
        "and other compatible agents. Invoke them as `/name` where your workspace supports it, or describe the task and the agent picks the skill.",
        "",
        "Install them with `./install.sh` (every detected workspace) or `./install.sh --target <workspace>`.",
        "",
    ]
    seen = set()
    for title, rows in groups:
        rows = [(n, s) for n, s in rows if n not in seen]
        if not rows:
            continue
        out += ["---", "", f"## {title}", ""]
        for name, summary in rows:
            seen.add(name)
            fm = meta.get(name)
            out.append(f"### `/{name}`")
            if fm is None:
                out += [f"**Missing:** no `skills/{name}.md` file.", ""]
                continue
            out += [fm.get("description", summary), ""]
            hint = fm.get("argument-hint")
            if hint:
                out += ["```", f"/{name} <{hint}>", "```", ""]
    missing = sorted(set(meta) - seen)
    if missing:
        out += ["---", "", "## Not yet grouped in README", ""]
        for name in missing:
            out += [f"### `/{name}`", "", meta[name].get("description", ""), ""]
    return "\n".join(out).rstrip() + "\n"


ROSTER_RE = re.compile(r"(<!-- BEGIN ROSTER[^\n]*-->\n)(.*?)(<!-- END ROSTER -->)", re.S)


def founder_doc():
    path = ROOT / "agents" / "founder.md"
    text = path.read_text(encoding="utf-8")
    groups = readme_groups("## The Team", r"^\| `([a-z0-9-]+)` \| (.+?) \|$")
    lines, seen = [], {"founder"}
    for title, rows in groups:
        rows = [(n, s) for n, s in rows if n not in seen]
        if not rows:
            continue
        seen.update(n for n, _ in rows)
        lines += ["", f"### {title}", "| Agent | Call When |", "|---|---|"]
        lines += [f"| `{n}` | {s} |" for n, s in rows]
    if not ROSTER_RE.search(text):
        raise SystemExit("agents/founder.md is missing the ROSTER markers")
    return ROSTER_RE.sub(lambda m: m.group(1) + "\n".join(lines).lstrip("\n") + "\n" + m.group(3), text)


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, content in (
        ("docs/agents.md", agents_doc()),
        ("docs/skills.md", skills_doc()),
        ("agents/founder.md", founder_doc()),
    ):
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        if check:
            stale.append(rel)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("out of date: " + ", ".join(stale) + " — run scripts/gen-docs.py", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
